"""Generates tests/common/faulty.rs: a GraphDB decorator that forwards every
method to an inner store and can be told to fail (a simulated crash).

The ONLY change to tests/ the service's implementer may make is to rerun this
script when the GraphDB trait changes (new methods), from the repository root:

    python crates/sovereign-docs/tests/common/gen_faulty.py \
        crates/sovereign-db/src/traits.rs \
        crates/sovereign-docs/tests/common/faulty.rs

It is mechanical: every trait method becomes `gate(name)?` then a call to the
inner store with the same arguments.
"""
import re
import sys

HEADER = '''//! GENERATED by tests/common/gen_faulty.py from crates/sovereign-db/src/traits.rs.
//! Do not edit by hand: rerun the generator when the GraphDB trait changes
//! (see TESTS.md, "Changing tests/").
//!
//! `FaultyDb` forwards every `GraphDB` call to `inner`, records its name, and
//! fails every call once the armed budget is spent — a simulated crash: the
//! process stops issuing writes at an arbitrary point. It can also fail one
//! single call and let every later call through (`fail_once_after`) — a
//! transient failure the caller survives and can clean up after (added
//! 2026-10-17 for S5-10, all or nothing).
#![allow(dead_code, clippy::too_many_arguments)]

use std::sync::atomic::{AtomicBool, AtomicI64, Ordering};
use std::sync::{Arc, Mutex};

use async_trait::async_trait;
use chrono::{DateTime, Utc};
use sovereign_db::error::{DbError, DbResult};
use sovereign_db::schema::*;
use sovereign_db::traits::GraphDB;

pub struct FaultyDb {
    pub inner: Arc<dyn GraphDB>,
    /// Calls left before the crash; negative = disarmed.
    budget: AtomicI64,
    /// Calls left before the one failing call; negative = disarmed.
    one_shot: AtomicI64,
    one_shot_fired: AtomicBool,
    calls: Mutex<Vec<&'static str>>,
}

impl FaultyDb {
    pub fn new(inner: Arc<dyn GraphDB>) -> Self {
        Self {
            inner,
            budget: AtomicI64::new(-1),
            one_shot: AtomicI64::new(-1),
            one_shot_fired: AtomicBool::new(false),
            calls: Mutex::new(Vec::new()),
        }
    }

    /// From now on, let `n` calls through, fail the next one only, then let
    /// every call through again.
    pub fn fail_once_after(&self, n: i64) {
        self.one_shot_fired.store(false, Ordering::SeqCst);
        self.one_shot.store(n, Ordering::SeqCst);
    }

    /// Whether the one failing call happened.
    pub fn failed_once(&self) -> bool {
        self.one_shot_fired.load(Ordering::SeqCst)
    }

    /// From now on, let `n` calls through, then fail every call.
    pub fn crash_after(&self, n: i64) {
        self.budget.store(n, Ordering::SeqCst);
    }

    /// Stop failing: the crash budget and a one-shot fault that has not fired
    /// yet are both disarmed.
    pub fn disarm(&self) {
        self.budget.store(-1, Ordering::SeqCst);
        self.one_shot.store(-1, Ordering::SeqCst);
    }

    /// Whether the armed budget was exhausted (the crash happened).
    pub fn crashed(&self) -> bool {
        self.budget.load(Ordering::SeqCst) == 0
    }

    pub fn calls(&self) -> Vec<&'static str> {
        self.calls.lock().unwrap().clone()
    }

    fn gate(&self, name: &'static str) -> DbResult<()> {
        self.calls.lock().unwrap().push(name);
        loop {
            let f = self.one_shot.load(Ordering::SeqCst);
            if f < 0 {
                break;
            }
            if self
                .one_shot
                .compare_exchange(f, f - 1, Ordering::SeqCst, Ordering::SeqCst)
                .is_ok()
            {
                if f == 0 {
                    self.one_shot_fired.store(true, Ordering::SeqCst);
                    return Err(DbError::Query(format!("injected fault at {name}")));
                }
                break;
            }
        }
        loop {
            let b = self.budget.load(Ordering::SeqCst);
            if b < 0 {
                return Ok(());
            }
            if b == 0 {
                return Err(DbError::Query(format!("injected crash at {name}")));
            }
            if self
                .budget
                .compare_exchange(b, b - 1, Ordering::SeqCst, Ordering::SeqCst)
                .is_ok()
            {
                return Ok(());
            }
        }
    }
}

#[async_trait]
impl GraphDB for FaultyDb {
'''

FOOTER = '}\n'


def main(traits_path, out_path):
    src = open(traits_path, encoding='utf-8').read()
    body = src[src.index('pub trait GraphDB'):]
    pat = re.compile(r'async fn\s+(\w+)\s*\((.*?)\)\s*->\s*(.*?)\s*([;{])', re.S)
    out = []
    for m in pat.finditer(body):
        name, args, ret = m.group(1), m.group(2), m.group(3)
        args_clean = ' '.join(args.split()).rstrip(',').strip()
        # Paths relative to sovereign-db's own crate root.
        args_clean = args_clean.replace('crate::', 'sovereign_db::')
        parts, depth, cur = [], 0, ''
        for ch in args_clean:
            if ch in '<([':
                depth += 1
            if ch in '>)]':
                depth -= 1
            if ch == ',' and depth == 0:
                parts.append(cur.strip())
                cur = ''
            else:
                cur += ch
        if cur.strip():
            parts.append(cur.strip())
        names = [p.split(':')[0].strip() for p in parts if not p.startswith('&self')]
        ret = ' '.join(ret.split()).replace('crate::', 'sovereign_db::')
        out.append(
            f"    async fn {name}({args_clean}) -> {ret} {{\n"
            f"        self.gate(\"{name}\")?;\n"
            f"        self.inner.{name}({', '.join(names)}).await\n"
            f"    }}\n"
        )
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER + ''.join(out) + FOOTER)
    sys.stderr.write(f"{len(out)} methods\n")


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
